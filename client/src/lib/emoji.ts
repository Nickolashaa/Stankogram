const EMOJI_ONLY_PATTERN =
  /^(?:\p{Extended_Pictographic}|\p{Emoji_Modifier}|\p{Regional_Indicator}|\u200D|\uFE0F|\s)+$/u

const HAS_PICTOGRAPHIC_PATTERN = /\p{Extended_Pictographic}/u

const MAX_LARGE_EMOJI_COUNT = 3

const segmenter =
  typeof Intl !== "undefined" && "Segmenter" in Intl
    ? new Intl.Segmenter(undefined, { granularity: "grapheme" })
    : null

function countGraphemes(text: string): number {
  if (segmenter === null) {
    return [...text].length
  }
  return [...segmenter.segment(text)].length
}

export function isLargeEmojiMessage(text: string): boolean {
  const trimmed = text.trim()

  if (trimmed === "" || !HAS_PICTOGRAPHIC_PATTERN.test(trimmed)) {
    return false
  }

  if (!EMOJI_ONLY_PATTERN.test(trimmed)) {
    return false
  }

  return countGraphemes(trimmed.replace(/\s/gu, "")) <= MAX_LARGE_EMOJI_COUNT
}

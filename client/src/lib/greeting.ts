export type DayPeriod = "morning" | "day" | "evening" | "night"

export function getDayPeriod(hour: number): DayPeriod {
  if (hour >= 5 && hour < 12) {
    return "morning"
  }
  if (hour >= 12 && hour < 18) {
    return "day"
  }
  if (hour >= 18 && hour < 23) {
    return "evening"
  }
  return "night"
}

const POOLS: Record<DayPeriod, string[]> = {
  morning: MORNING,
  day: DAY,
  evening: EVENING,
  night: NIGHT,
}

function poolForHour(hour: number): string[] {
  return POOLS[getDayPeriod(hour)]
}

export function getGreeting(name: string, now: Date = new Date()): string {
  const pool = poolForHour(now.getHours())
  const template = pool[Math.floor(Math.random() * pool.length)] ?? pool[0]!
  return template.replace("{name}", name)
}
